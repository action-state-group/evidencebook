// The shared standard_history/1 responder fixture (evidencebook#328): Go
// writes it from a real book, and the Python and Rust responders build the
// same book from its recipe (the same keys, clock and records) and answer
// the same requests with the same reply octets.

const standardHistoryVectorsPath = "testdata/standard-history-respond/vectors.json"

type standardHistoryVectorEntry struct {
	RecordType      string          `json:"record_type"`
	EpistemicType   string          `json:"epistemic_type"`
	CounterpartyRef string          `json:"counterparty_ref,omitempty"`
	Statement       json.RawMessage `json:"statement,omitempty"`
}

type standardHistoryVectorCase struct {
	Name      string `json:"name"`
	Requester string `json:"requester,omitempty"`
	Request   string `json:"request"`
	// Outcome is "artifact" or the refusal reason; Reply is the reply octets.
	Outcome  string `json:"outcome"`
	Artifact string `json:"artifact,omitempty"`
	Reply    string `json:"reply"`
}

type standardHistoryVectorScenario struct {
	Name       string `json:"name"`
	HolderKind string `json:"holder_kind"`
	// Source is false for a book whose host supplies no inputs.
	Source bool                        `json:"source"`
	Pin    string                      `json:"pin"`
	Cases  []standardHistoryVectorCase `json:"cases"`
}

type standardHistoryVectors struct {
	Comment    string `json:"comment"`
	SignerSeed string `json:"signer_seed"`
	LogSeed    string `json:"log_seed"`
	BookID     string `json:"book_id"`
	Operator   string `json:"operator"`
	LogID      string `json:"log_id"`
	// Start is the clock before its first reading; each reading is one
	// second later.
	Start string `json:"start"`
	// Policy is what the host's inputs return with every deal_terms
	// record's statement, its record id as the deal and its committed_at as
	// agreed_at.
	PolicyDigest string                          `json:"policy_digest"`
	PolicyMonths int                             `json:"policy_months"`
	Entries      []standardHistoryVectorEntry    `json:"entries"`
	Scenarios    []standardHistoryVectorScenario `json:"scenarios"`
}

func TestStandardHistoryRespondVectors(t *testing.T) {
	ctx := context.Background()
	v := standardHistoryVectors{
		Comment:      "standard_history/1 answered by a Book (StandardHistorySource): generated by TestStandardHistoryRespondVectors from a real Go book; the Python and Rust responders build the same book from this recipe and give the same reply octets for each case, in order.",
		SignerSeed:   hex.EncodeToString(seededKey(9).Seed()),
		LogSeed:      hex.EncodeToString(seededKey(109).Seed()),
		BookID:       "book-sh",
		Operator:     "book-sh-operator",
		LogID:        "book-sh-log",
		Start:        "2026-09-26T12:00:00Z",
		PolicyDigest: testPolicy.Digest,
		PolicyMonths: testPolicy.Window.Months,
		Entries: []standardHistoryVectorEntry{
			{"deal_terms", "producer_claim", "carol", json.RawMessage(`{"role":"provided","amount":{"value":"2500","assetCode":"USD","assetScale":2},"outcome":"held","happened":"stamped_by_both","disputes":[]}`)},
			{"deal_terms", "producer_claim", "carol", json.RawMessage(`{"role":"bought","amount":{"value":"999","assetCode":"USD","assetScale":2},"outcome":"undecided","happened":"receipt_only","disputes":[{"side":"raised","outcome":"open","forum":"rail"}]}`)},
			{"deal_terms", "producer_claim", "carol", json.RawMessage(`{"counterparty_class":"shop_preauth","role":"bought","amount":{"value":"120","assetCode":"EUR","assetScale":0},"outcome":"held","happened":"no_record","disputes":[]}`)},
			{"observation", "observed_event", "", nil},
		},
	}
	inputs := func(_ context.Context, _ Checkpoint, records []Record) (standardhistory.Policy, []standardhistory.Deal, error) {
		return dealsOf(nil)(ctx, Checkpoint{}, records)
	}
	subject := func(kind SubjectKind) Subject {
		if kind == SubjectRange {
			return Subject{Kind: SubjectRange, Range: [2]uint64{0, 1}}
		}
		return Subject{Kind: kind}
	}
	type ask struct {
		name, requester string
		kind            SubjectKind
	}
	scenarios := []struct {
		name, holderKind string
		source           bool
		asks             []ask
	}{
		{"person", "person", true, []ask{
			{"counterparty", "carol", SubjectFullHistory},
			{"identified", "mallory", SubjectFullHistory},
			{"stranger", "", SubjectFullHistory},
			{"range-subject", "carol", SubjectRange},
		}},
		{"node", "node", true, []ask{{"counterparty", "carol", SubjectFullHistory}}},
		{"no-source", "person", false, []ask{{"counterparty", "carol", SubjectFullHistory}, {"stranger", "", SubjectFullHistory}}},
	}
	for _, s := range scenarios {
		f := newFixture(t, "book-sh", 9)
		cfg := f.config(t)
		if s.source {
			cfg.StandardHistory = &StandardHistorySource{HolderKind: s.holderKind, Inputs: inputs}
		}
		book, err := Open(ctx, cfg)
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { _ = book.Release() })
		for _, e := range v.Entries {
			mustAppend(t, book, Entry{RecordType: e.RecordType, EpistemicType: EpistemicType(e.EpistemicType), CounterpartyRef: e.CounterpartyRef, Statement: e.Statement})
		}
		out := standardHistoryVectorScenario{Name: s.name, HolderKind: s.holderKind, Source: s.source, Pin: anchorPin(t, book)}
		for _, a := range s.asks {
			req := jsonRequest(t, EvidenceRequest{Subject: subject(a.kind), Derivation: DerivationStandardHistory, Coverage: Coverage{ExpectedPin: out.Pin}})
			reply, _ := respondWith(t, book, req, RespondOptions{AuthenticatedRequester: a.requester, Policy: DefaultSharePolicy()})
			c := standardHistoryVectorCase{Name: a.name, Requester: a.requester, Request: string(req.Octets), Reply: string(reply.Octets)}
			if reply.Envelope != nil {
				c.Outcome, c.Artifact = "artifact", string(mustEnvelope(t, reply).Artifact)
			} else {
				c.Outcome = reply.Refusal.Reason
			}
			out.Cases = append(out.Cases, c)
		}
		v.Scenarios = append(v.Scenarios, out)
	}

	got, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	got = append(got, '\n')
	if os.Getenv("EVIDENCEBOOK_WRITE_STANDARD_HISTORY_VECTORS") != "" {
		if err := os.MkdirAll(filepath.Dir(standardHistoryVectorsPath), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(standardHistoryVectorsPath, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(standardHistoryVectorsPath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s differs from what the book answers; EVIDENCEBOOK_WRITE_STANDARD_HISTORY_VECTORS=1 rewrites it", standardHistoryVectorsPath)
	}
}
