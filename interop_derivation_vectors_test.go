// derivationVectorsPath is the shared fixture for definition-digest
// derivations: this test answers it from a real book, and the Rust crate's
// tests/derivation.rs answers the same requests over the same records and
// must give the same bytes. EVIDENCEBOOK_WRITE_DERIVATION_VECTORS=1 rewrites
// it.
var derivationVectorsPath = filepath.Join("testdata", "derivation", "vectors.json")

type derivationVectorDefinition struct {
	Name        string        `json:"name"`
	Document    string        `json:"document"`
	DocumentJCS string        `json:"document_jcs"`
	ID          string        `json:"id"`
	Recipient   string        `json:"recipient,omitempty"`
	Forms       []SubjectKind `json:"forms"`
	Fields      []string      `json:"fields"`
}

// derivationVectorReregistration registers Definition's document again with
// the declarations given here. Outcome is "registered" (the same
// identifier, nothing changed) or "refused" (ErrInvalid).
type derivationVectorReregistration struct {
	Name       string        `json:"name"`
	Definition string        `json:"definition"`
	Document   string        `json:"document"`
	Recipient  string        `json:"recipient,omitempty"`
	Forms      []SubjectKind `json:"forms"`
	Fields     []string      `json:"fields"`
	Outcome    string        `json:"outcome"`
}

type derivationVectorRecord struct {
	LeafIndex   uint64          `json:"leaf_index"`
	Digest      string          `json:"digest"`
	Header      json.RawMessage `json:"header"`
	Body        string          `json:"body"`
	Correlation string          `json:"correlation"`
}

type derivationVectorCase struct {
	Name       string `json:"name"`
	Definition string `json:"definition,omitempty"`
	Requester  string `json:"requester,omitempty"`
	Request    string `json:"request"`
	// Outcome is "artifact" or the refusal reason; Reply is the reply
	// octets either way.
	Outcome        string `json:"outcome"`
	Artifact       string `json:"artifact,omitempty"`
	ArtifactDigest string `json:"artifact_digest,omitempty"`
	Reply          string `json:"reply,omitempty"`
}

type derivationVectors struct {
	Comment       string                       `json:"comment"`
	ResponderSeed string                       `json:"responder_seed"`
	Definitions   []derivationVectorDefinition `json:"definitions"`
	Book          struct {
		EvidenceStream string                   `json:"evidence_stream"`
		Statement      string                   `json:"anchor_statement"`
		Anchor         string                   `json:"anchor"`
		TreeSize       uint64                   `json:"tree_size"`
		Entries        uint64                   `json:"entries"`
		IssuedAt       string                   `json:"issued_at"`
		Records        []derivationVectorRecord `json:"records"`
	} `json:"book"`
	Rejected     []derivationVectorDefinition     `json:"rejected"`
	Reregistered []derivationVectorReregistration `json:"reregistered"`
	Cases        []derivationVectorCase           `json:"cases"`
}

// TestDerivationVectors builds the shared derivation fixture from a real
// book and requires it byte for byte.
func TestDerivationVectors(t *testing.T) {
	ctx := context.Background()
	book, records := linkedBook(t)
	cp, err := book.Checkpoint(ctx)
	if err != nil {
		t.Fatal(err)
	}
	pin := anchorDigest(cp)

	var v derivationVectors
	v.Comment = "Definition-digest derivations (Book.RegisterDerivation, interop_derivation.go): generated by TestDerivationVectors from a real Go book; the Rust crate's tests/derivation.rs gives the same ids and the same reply octets."
	v.ResponderSeed = hex.EncodeToString(seededKey(1).Seed())
	v.Book.EvidenceStream, v.Book.Statement, v.Book.Anchor = cp.LogID, hex.EncodeToString(cp.Statement), pin
	v.Book.TreeSize, v.Book.Entries, v.Book.IssuedAt = cp.TreeSize, cp.Entries, cp.IssuedAt.UTC().Format("2006-01-02T15:04:05Z")
	for leaf, id := range book.order[:cp.Entries] {
		stored, err := book.storedLocked(ctx, id)
		if err != nil {
			t.Fatal(err)
		}
		body, err := capsulePreimage(stored.Capsule, id)
		if err != nil {
			t.Fatal(err)
		}
		v.Book.Records = append(v.Book.Records, derivationVectorRecord{
			LeafIndex: uint64(leaf), Digest: id, Header: stored.Header, Body: hex.EncodeToString(body),
			Correlation: correlationOf(book.records[id].Header),
		})
	}

	// The documents are not in canonical form: the identifier is the digest
	// of their JCS, whatever the holder's spacing and member order.
	defs := []derivationVectorDefinition{
		{
			Name:      "for-alice",
			Document:  "{ \"recipient\": \"alice\",\n  \"computation\": \"project\", \"fields\": [\"record_type\", \"committed_at\", \"links\"] }",
			Recipient: "alice", Forms: []SubjectKind{SubjectCorrelation, SubjectRecord},
			Fields: []string{"record_type", "committed_at", "links"},
		},
		{
			Name:     "shared",
			Document: `{"fields":["seq","subject_ref","epistemic_type","event_time_claim"],"computation":"project","note":"café 😀"}`,
			Forms:    []SubjectKind{SubjectRange, SubjectFullHistory, SubjectCorrelation},
			Fields:   []string{"seq", "subject_ref", "epistemic_type", "event_time_claim"},
		},
		{
			// At the reader's limits: -0 is the integer 0, and a value at
			// depth 32 (the document is depth 0) is read.
			Name:     "limits",
			Document: `{"zero":-0,"deep":` + strings.Repeat("[", 32) + strings.Repeat("]", 32) + `}`,
			Forms:    []SubjectKind{SubjectRecord},
			Fields:   []string{"v"},
		},
		{
			// A member named as serde_json names its private number is an
			// ordinary member.
			Name:     "private-member",
			Document: `{"x":{"$serde_json::private::Number":"1.5"},"$serde_json::private::Number":1}`,
			Forms:    []SubjectKind{SubjectRecord},
			Fields:   []string{"v"},
		},
	}
	byName := map[string]string{}
	for i, def := range defs {
		id, err := book.RegisterDerivation(DerivationDefinition{Document: []byte(def.Document), Recipient: def.Recipient, Forms: def.Forms, Fields: def.Fields})
		if err != nil {
			t.Fatal(err)
		}
		decoded, err := evidencerequest.DecodeJSON([]byte(def.Document))
		if err != nil {
			t.Fatal(err)
		}
		jcs, err := evidencerequest.EncodeJCS(decoded)
		if err != nil {
			t.Fatal(err)
		}
		defs[i].ID, defs[i].DocumentJCS = id, string(jcs)
		if digestBytes(jcs) != id {
			t.Fatal("the identifier is not the digest of the document's JCS")
		}
		byName[def.Name] = id
	}
	v.Definitions = defs

	// Every one of these is refused registration (ErrInvalid).
	v.Rejected = []derivationVectorDefinition{
		{Name: "not-an-object", Document: `["project"]`, Forms: []SubjectKind{SubjectRecord}, Fields: []string{"seq"}},
		{Name: "not-json", Document: `{"computation":`, Forms: []SubjectKind{SubjectRecord}, Fields: []string{"seq"}},
		{Name: "duplicate-member", Document: `{"a":1,"a":2}`, Forms: []SubjectKind{SubjectRecord}, Fields: []string{"seq"}},
		{Name: "duplicate-member-escaped", Document: `{"a":1,"\u0061":2}`, Forms: []SubjectKind{SubjectRecord}, Fields: []string{"seq"}},
		{Name: "too-deep", Document: `{"deep":` + strings.Repeat("[", 33) + strings.Repeat("]", 33) + `}`, Forms: []SubjectKind{SubjectRecord}, Fields: []string{"seq"}},
		{Name: "trailing-data", Document: `{} {}`, Forms: []SubjectKind{SubjectRecord}, Fields: []string{"seq"}},
		{Name: "leading-zero", Document: `{"a":01}`, Forms: []SubjectKind{SubjectRecord}, Fields: []string{"seq"}},
		{Name: "duplicate-in-private-member", Document: `{"$serde_json::private::Number":{"a":1,"a":2}}`, Forms: []SubjectKind{SubjectRecord}, Fields: []string{"seq"}},
		{Name: "fraction", Document: `{"weight":1.5}`, Forms: []SubjectKind{SubjectRecord}, Fields: []string{"seq"}},
		{Name: "unsafe-integer", Document: `{"n":9007199254740992}`, Forms: []SubjectKind{SubjectRecord}, Fields: []string{"seq"}},
		{Name: "no-forms", Document: `{}`, Fields: []string{"seq"}},
		{Name: "no-fields", Document: `{}`, Forms: []SubjectKind{SubjectRecord}},
		{Name: "over-checkpoints", Document: `{}`, Forms: []SubjectKind{SubjectCheckpoints}, Fields: []string{"seq"}},
		{Name: "unknown-form", Document: `{}`, Forms: []SubjectKind{"everything"}, Fields: []string{"seq"}},
		{Name: "not-a-header-member", Document: `{}`, Forms: []SubjectKind{SubjectRecord}, Fields: []string{"payload"}},
	}
	for _, def := range v.Rejected {
		if _, err := book.RegisterDerivation(DerivationDefinition{Document: []byte(def.Document), Forms: def.Forms, Fields: def.Fields}); err == nil {
			t.Fatalf("%s: registered", def.Name)
		}
	}

	// A definition registered again (#86), before the cases: they are
	// answered as the first registration declared, so a refused one changed
	// nothing.
	alice := defs[0]
	v.Reregistered = []derivationVectorReregistration{
		{Name: "same-declarations", Document: alice.Document, Recipient: "alice", Forms: alice.Forms, Fields: alice.Fields, Outcome: "registered"},
		{Name: "same-sets-other-order", Document: alice.DocumentJCS, Recipient: "alice", Forms: []SubjectKind{SubjectRecord, SubjectCorrelation, SubjectRecord}, Fields: []string{"links", "record_type", "committed_at"}, Outcome: "registered"},
		{Name: "other-recipient", Document: alice.Document, Recipient: "bob", Forms: alice.Forms, Fields: alice.Fields, Outcome: "refused"},
		{Name: "no-recipient", Document: alice.Document, Forms: alice.Forms, Fields: alice.Fields, Outcome: "refused"},
		{Name: "fewer-forms", Document: alice.Document, Recipient: "alice", Forms: []SubjectKind{SubjectRecord}, Fields: alice.Fields, Outcome: "refused"},
		{Name: "more-fields", Document: alice.Document, Recipient: "alice", Forms: alice.Forms, Fields: append(slices.Clone(alice.Fields), "seq"), Outcome: "refused"},
		{Name: "recipient-for-shared", Document: defs[1].Document, Recipient: "alice", Forms: defs[1].Forms, Fields: defs[1].Fields, Outcome: "refused"},
	}
	for i := range v.Reregistered {
		r := &v.Reregistered[i]
		r.Definition = "for-alice"
		if r.Name == "recipient-for-shared" {
			r.Definition = "shared"
		}
		id, err := book.RegisterDerivation(DerivationDefinition{Document: []byte(r.Document), Recipient: r.Recipient, Forms: r.Forms, Fields: r.Fields})
		switch r.Outcome {
		case "registered":
			if err != nil || id != byName[r.Definition] {
				t.Fatalf("%s: %q, %v", r.Name, id, err)
			}
		default:
			if !errors.Is(err, ErrInvalid) || id != "" {
				t.Fatalf("%s: %q, %v", r.Name, id, err)
			}
		}
	}

	correlation := Subject{Kind: SubjectCorrelation, Correlation: "order-17"}
	cases := []struct {
		name, definition, requester string
		subject                     Subject
	}{
		{"recipient-correlation", "for-alice", "alice", correlation},
		{"recipient-record", "for-alice", "alice", Subject{Kind: SubjectRecord, Digest: records[1].RecordID}},
		{"other-requester", "for-alice", "bob", correlation},
		{"unauthenticated", "for-alice", "", correlation},
		{"undeclared-form", "for-alice", "alice", Subject{Kind: SubjectRange, Range: [2]uint64{0, 1}}},
		// Authorization comes before the form (evidencerequest.Decide).
		{"other-requester-undeclared-form", "for-alice", "bob", Subject{Kind: SubjectRange, Range: [2]uint64{0, 1}}},
		{"shared-range", "shared", "carol", Subject{Kind: SubjectRange, Range: [2]uint64{0, 2}}},
		{"shared-correlation", "shared", "alice", correlation},
		{"shared-checkpoints", "shared", "alice", Subject{Kind: SubjectCheckpoints}},
		// The share policy refuses an unauthenticated requester before the
		// form is read.
		{"shared-unauthenticated-checkpoints", "shared", "", Subject{Kind: SubjectCheckpoints}},
		{"underived-correlation", "", "alice", correlation},
		{"unregistered", digestBytes([]byte("no such definition")), "alice", correlation},
	}
	for _, c := range cases {
		derivation := c.definition
		if id, ok := byName[c.definition]; ok {
			derivation = id
		}
		req := jsonRequest(t, EvidenceRequest{Subject: c.subject, Derivation: derivation, Coverage: Coverage{ExpectedPin: pin}})
		reply := respondAs(t, book, req, c.requester)
		out := derivationVectorCase{Name: c.name, Definition: c.definition, Requester: c.requester, Request: string(req.Octets)}
		if reply.Envelope != nil {
			e := mustEnvelope(t, reply)
			out.Outcome, out.Artifact, out.ArtifactDigest, out.Reply = "artifact", string(e.Artifact), e.ArtifactDigest, string(reply.Octets)
		} else {
			out.Outcome, out.Reply = reply.Refusal.Reason, string(reply.Octets)
		}
		v.Cases = append(v.Cases, out)
	}

	got, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	got = append(got, '\n')
	if os.Getenv("EVIDENCEBOOK_WRITE_DERIVATION_VECTORS") != "" {
		if err := os.MkdirAll(filepath.Dir(derivationVectorsPath), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(derivationVectorsPath, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(derivationVectorsPath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s differs from what the book answers; EVIDENCEBOOK_WRITE_DERIVATION_VECTORS=1 rewrites it", derivationVectorsPath)
	}
}
